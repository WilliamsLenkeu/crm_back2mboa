export const dictionaries = { fr, en };
export type Dict = { [K in keyof typeof fr]: string };

export function t(locale: Locale): Dict {
  return dictionaries[locale] || dictionaries.fr;
}

/** Labels d’affichage — valeurs DB inchangées */
export function stageLabel(etape: string, d: Dict): string {
  const map: Record<string, string> = {
    "01_Nouveau": d.stageNouveau,
    "02_Contacté": d.stageContacte,
    "03_Qualifié": d.stageQualifie,
    "04_Engagé": d.stageEngage,
    "05_Partenaire": d.stagePartenaire,
    "06_Pause": d.stagePause,
  };
  return map[etape] || etape.replace(/^\d+_/, "").replace(/_/g, " ");
}

export function prioLabel(value: string | null | undefined, d: Dict): string {
  if (value === "Haute") return d.prioHaute;
  if (value === "Basse") return d.prioBasse;
  if (value === "Moyenne") return d.prioMoyenne;
  return value || "—";
}
